// Helper to retrieve curriculum by class
export function getOfficialSubjectsForClass(classLevel: StudentClass): AcademicSubject[] {
  if (classLevel === '12') return OFFICIAL_SUBJECTS_CLASS_12;
  if (classLevel === '10') return OFFICIAL_SUBJECTS_CLASS_10;
  // Fallbacks for Class 11 and Class 9 mapped logically
  if (classLevel === '11') {
    return OFFICIAL_SUBJECTS_CLASS_12.map((s) => ({
      ...s,
      classLevel: '11',
      chapters: s.chapters.slice(0, 8).map((ch, i) => ({
        ...ch,
        id: `c11_${s.name.toLowerCase()}_${i + 1}`,
        classLevel: '11',
        name: `Class 11 ${s.name} Part ${i + 1}: ${ch.name}`,
      })),
    }));
  }
  // Class 9 mapped from Class 10
  return OFFICIAL_SUBJECTS_CLASS_10.map((s) => ({
    ...s,
    classLevel: '9',
    chapters: s.chapters.slice(0, 8).map((ch, i) => ({
      ...ch,
      id: `c9_${s.name.toLowerCase()}_${i + 1}`,
      classLevel: '9',
      name: `Class 9 ${s.name} Unit ${i + 1}: ${ch.name}`,
    })),
  }));
}
